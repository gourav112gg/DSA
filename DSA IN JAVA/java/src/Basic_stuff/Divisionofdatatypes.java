package Basic_stuff;

public class Divisionofdatatypes {
    static void main() {
        double x = 5/2; // internally dekhta hai int by int hai tah return ve int hee ayunda ae
        System.out.println(x);
        x = 5.0/2; // internally dekhta hai decimal by int or decimal by decimal hai to proper division hunde ae
        System.out.println(x);
    }
}
